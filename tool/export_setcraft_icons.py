"""Export shared vector geometry and platform icons. Requires Python + Pillow.

This owns the paths shared by Android VectorDrawable, Flutter CustomPaint, SVG
and final-size PNG exports. The generated concept bitmap is not a runtime input.
"""
from pathlib import Path
import json
import math
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
POINTS = [(674, 412), (618, 356), (438, 356), (384, 410),
          (640, 610), (586, 664), (406, 664), (350, 608)]
PATH = 'M ' + ' L '.join(f'{x},{y}' for x, y in POINTS)
CIRCLE = 'M 862,512 A 350,350 0 1,0 162,512 A 350,350 0 1,0 862,512'
RING_STROKE, S_STROKE = 24, 32
LANCZOS = Image.Resampling.LANCZOS


def render(size):
    """Draw directly at each output size, with 4x edge antialiasing."""
    scale = size * 4 / 1024
    image = Image.new('RGB', (size * 4, size * 4), 'black')
    draw = ImageDraw.Draw(image)
    box = lambda r: tuple(v * scale for v in (512-r, 512-r, 512+r, 512+r))
    draw.ellipse(box(350 + RING_STROKE / 2), fill='white')
    draw.ellipse(box(350 - RING_STROKE / 2), fill='black')
    normals = []
    polygon = lambda points: draw.polygon(
        [(x * scale, y * scale) for x, y in points], fill='white')
    for p, q in zip(POINTS, POINTS[1:]):
        dx, dy = q[0] - p[0], q[1] - p[1]
        length = math.hypot(dx, dy)
        nx, ny = -dy / length * S_STROKE / 2, dx / length * S_STROKE / 2
        normals.append((nx, ny))
        polygon([(p[0]+nx, p[1]+ny), (p[0]-nx, p[1]-ny),
                 (q[0]-nx, q[1]-ny), (q[0]+nx, q[1]+ny)])
    for p, a, b in zip(POINTS[1:-1], normals, normals[1:]):
        for sign in [-1, 1]:
            polygon([p, (p[0]+sign*a[0], p[1]+sign*a[1]),
                     (p[0]+sign*b[0], p[1]+sign*b[1])])
    return image.resize((size, size), LANCZOS)


def save(target, size):
    target.parent.mkdir(parents=True, exist_ok=True)
    render(size).save(target, optimize=True)


save(ROOT / 'assets/branding/setcraft-icon.png', 1024)
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <rect width="1024" height="1024" fill="#000"/>
  <g fill="none" stroke="#fff" stroke-linecap="butt" stroke-linejoin="bevel">
    <circle cx="512" cy="512" r="350" stroke-width="{RING_STROKE}"/>
    <path d="{PATH}" stroke-width="{S_STROKE}"/>
  </g>
</svg>
'''
(ROOT / 'assets/branding/setcraft-mark.svg').write_text(svg, encoding='utf-8')
dart = "// Generated by tool/export_setcraft_icons.py. Do not edit by hand.\n"
dart += "import 'dart:ui';\n\nabstract final class SetcraftGeometry {\n"
dart += f'  static const ringStroke = {RING_STROKE}.0;\n'
dart += f'  static const symbolStroke = {S_STROKE}.0;\n'
dart += '  static Path symbol() => Path()\n'
dart += f'    ..moveTo({POINTS[0][0]}, {POINTS[0][1]})\n'
dart += '\n'.join(f'    ..lineTo({x}, {y})' for x, y in POINTS[1:]) + ';\n}\n'
(ROOT / 'lib/core/branding/setcraft_geometry.dart').write_text(dart, encoding='utf-8')

for platform in ['ios', 'macos']:
    folder = ROOT / platform / 'Runner/Assets.xcassets/AppIcon.appiconset'
    entries = json.loads((folder / 'Contents.json').read_text('utf-8'))['images']
    for entry in entries:
        side = round(float(entry['size'].split('x')[0]) * float(entry['scale'][:-1]))
        save(folder / entry['filename'], side)
launch = ROOT / 'ios/Runner/Assets.xcassets/LaunchImage.imageset'
for scale in [1, 2, 3]:
    suffix = '' if scale == 1 else f'@{scale}x'
    save(launch / f'LaunchImage{suffix}.png', 144 * scale)

res = ROOT / 'android/app/src/main/res'


def vector(name, dp, viewport=1024, offset=0):
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/export_setcraft_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{dp}dp" android:height="{dp}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
    <group android:translateX="{offset}" android:translateY="{offset}">
        <path android:pathData="{CIRCLE}" android:fillColor="#00000000"
            android:strokeColor="#FFFFFFFF" android:strokeWidth="{RING_STROKE}"/>
        <path android:pathData="{PATH}" android:fillColor="#00000000"
            android:strokeColor="#FFFFFFFF" android:strokeWidth="{S_STROKE}"
            android:strokeLineCap="butt" android:strokeLineJoin="bevel"/>
    </group>
</vector>
'''
    (res / f'drawable/{name}.xml').write_text(xml, encoding='utf-8')


# The 108dp adaptive layer is cropped to a 72dp launcher viewport. Keep the ring
# at 70% of that visible tile, with safe margins around the circle.
vector('setcraft_launcher_foreground', 108, 1536, 256)
vector('setcraft_launcher_monochrome', 108, 1536, 256)
vector('setcraft_splash_icon', 288, 2048, 512)
vector('setcraft_launch', 144)
vector('ic_notification', 24)
for density, scale in [('mdpi', 1), ('hdpi', 1.5), ('xhdpi', 2), ('xxhdpi', 3), ('xxxhdpi', 4)]:
    save(res / f'mipmap-{density}/ic_launcher.png', round(48 * scale))
    # Only remove these superseded generated rasters, whose resource names
    # would otherwise override the new vectors at matching densities.
    for name in ['setcraft_launch', 'setcraft_splash_icon', 'ic_notification']:
        (res / f'drawable-{density}/{name}.png').unlink(missing_ok=True)
for name in ['setcraft_launcher_foreground', 'setcraft_launcher_monochrome', 'setcraft_splash_icon']:
    (res / f'drawable-nodpi/{name}.png').unlink(missing_ok=True)

for size in [192, 512]:
    for name in [f'Icon-{size}.png', f'Icon-maskable-{size}.png']:
        save(ROOT / 'web/icons' / name, size)
save(ROOT / 'web/favicon.png', 32)
render(1024).save(ROOT / 'windows/runner/resources/app_icon.ico', format='ICO',
                  sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
print('Exported shared vector geometry and final-size platform icons.')
